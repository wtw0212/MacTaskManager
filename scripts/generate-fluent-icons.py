#!/usr/bin/env python3
"""Turns Fluent UI System Icons SVGs into SwiftUI Shapes (Views/FluentIcons.swift).

Usage: generate-fluent-icons.py <folder with @fluentui/svg-icons icons> <output .swift>
Needs: pip install svgelements
"""
import re
import sys
from svgelements import SVG, Path, Move, Line, CubicBezier, QuadraticBezier, Arc, Close

# case name in Swift -> Fluent icon base name (20px size)
ICONS = {
    "processes": "board",
    "performance": "pulse_square",
    "startup": "top_speed",
    "runTask": "window_new",
    "endTask": "prohibited",
    "refresh": "arrow_clockwise",
    "enable": "checkmark_circle",
    "chevronRight": "chevron_right",
    "search": "search",
    "menu": "navigation",
    "dismiss": "dismiss",
    "filter": "filter",
    "efficiency": "leaf_one",
    "pause": "pause",
    "view": "eye",
    "chevronDown": "chevron_down",
    "history": "history",
    "users": "people",
    "user": "person",
    "services": "puzzle_cube",
    "start": "play",
    "stop": "stop",
    "delete": "delete",
}
STYLES = ["regular", "filled"]


def num(v):
    return f"{v:.3f}".rstrip("0").rstrip(".")


def pt(p):
    return f"CGPoint(x: {num(p.x)}, y: {num(p.y)})"


def swift_path(d):
    lines = []
    for seg in Path(d):
        if isinstance(seg, Move):
            lines.append(f"p.move(to: {pt(seg.end)})")
        elif isinstance(seg, Close):
            lines.append("p.closeSubpath()")
        elif isinstance(seg, Line):
            lines.append(f"p.addLine(to: {pt(seg.end)})")
        elif isinstance(seg, QuadraticBezier):
            lines.append(f"p.addQuadCurve(to: {pt(seg.end)}, control: {pt(seg.control)})")
        elif isinstance(seg, CubicBezier):
            lines.append(f"p.addCurve(to: {pt(seg.end)}, control1: {pt(seg.control1)}, control2: {pt(seg.control2)})")
        elif isinstance(seg, Arc):
            for c in seg.as_cubic_curves():
                lines.append(f"p.addCurve(to: {pt(c.end)}, control1: {pt(c.control1)}, control2: {pt(c.control2)})")
    return lines


def main():
    folder, output = sys.argv[1], sys.argv[2]
    out = [
        "// Generated by scripts/generate-fluent-icons.py from Fluent UI System Icons",
        "// (https://github.com/microsoft/fluentui-system-icons), MIT License, Copyright (c) 2020 Microsoft Corporation.",
        "// See LICENSES/FluentUI-System-Icons.txt. Do not edit by hand.",
        "",
        "import SwiftUI",
        "",
        "enum FluentIcon: String {",
    ]
    out += [f"    case {name}" for name in ICONS]
    out += ["}", "", "/// A Fluent icon drawn from its 20x20 vector outline, scaled to fit.", "struct FluentIconShape: Shape {",
            "    var icon: FluentIcon", "    var filled = false", "",
            "    func path(in rect: CGRect) -> Path {",
            "        let scale = min(rect.width, rect.height) / 20",
            "        let base = filled ? Self.filled(icon) : Self.regular(icon)",
            "        return base.applying(CGAffineTransform(scaleX: scale, y: scale)",
            "            .concatenating(CGAffineTransform(translationX: rect.midX - 10 * scale, y: rect.midY - 10 * scale)))",
            "    }"]
    for style in STYLES:
        out += ["", f"    private static func {style}(_ icon: FluentIcon) -> Path {{", "        switch icon {"]
        for name, fluent in ICONS.items():
            svg = open(f"{folder}/{fluent}_20_{style}.svg").read()
            ds = re.findall(r'\sd="([^"]+)"', svg)
            out.append(f"        case .{name}:")
            out.append("            return Path { p in")
            for d in ds:
                out += ["                " + l for l in swift_path(d)]
            out.append("            }")
        out += ["        }", "    }"]
    out += ["}", "",
            "/// Fluent icon as a view, tinted with the current foreground style.",
            "struct Fluent: View {",
            "    var icon: FluentIcon",
            "    var filled = false",
            "    var size: CGFloat = 16", "",
            "    init(_ icon: FluentIcon, filled: Bool = false, size: CGFloat = 16) {",
            "        self.icon = icon",
            "        self.filled = filled",
            "        self.size = size",
            "    }", "",
            "    var body: some View {",
            "        FluentIconShape(icon: icon, filled: filled)",
            "            .frame(width: size, height: size)",
            "    }",
            "}", ""]
    open(output, "w").write("\n".join(out))


main()
